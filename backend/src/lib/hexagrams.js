const HEXAGRAMS = Object.entries(HEXAGRAM_DATA).map(([key, value]) => ({
  key,
  name: value.name,
  meaning: value.meaning,
  advice: value.advice,
  interpretation: `${value.meaning} ${value.advice}`,
  baseScores: buildBaseScores(value.score),
}));

function randomHexagram() {
  const idx = Math.floor(Math.random() * HEXAGRAMS.length);
  return HEXAGRAMS[idx];
}

function buildInterpretation(hexagram, category = "general") {
  const template = CATEGORY_TEMPLATES[category] || CATEGORY_TEMPLATES.general;
  return `${template.prefix}${hexagram.advice} ${template.suffix}`.trim();
}

